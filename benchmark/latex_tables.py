"""
LaTeX table generation — completely separate from the benchmark runner.

Reads the raw CSV files written by ``report_writer.py`` and produces
publication-ready booktabs tables in ``results/<experiment>/latex/``.
Like the figures, tables can be regenerated at any time from stored data:

    python -m benchmark.latex_tables --experiment family_comparison

Tables produced (one .tex file each, ready for \\input{} in the paper):
- latency.tex      mean ± stdev, median, p95 end-to-end latency
- cpu.tex          average / peak CPU utilisation
- memory.tex       average / peak RSS memory
- tokens.tex       mean prompt / completion / total tokens
- throughput.tex   requests per second per concurrency level
- routing.tex      routing accuracy per cell

The best (lowest latency / resource, highest accuracy or throughput) value
per model is set in bold so architecture winners are visible at a glance.
"""

import argparse
import csv
import sys
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional

_REPO_ROOT = Path(__file__).resolve().parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from benchmark.config import BenchmarkConfig, load_config  # noqa: E402
from benchmark.metrics import summarize  # noqa: E402

_ARCH_LABELS = {"single_agent": "Single agent + skills", "multi_agent": "Multi-agent"}


def _short_model(model: str) -> str:
    return model.split("/")[-1].replace("_", "\\_")


def _latest_run_id(raw_dir: Path) -> Optional[str]:
    candidates = sorted(
        (p for p in raw_dir.glob("*.csv") if not p.stem.endswith("_throughput")),
        key=lambda p: p.stat().st_mtime,
    )
    return candidates[-1].stem if candidates else None


def _load_rows(csv_path: Path) -> List[dict]:
    with open(csv_path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _values(rows: List[dict], key: str) -> List[float]:
    """Numeric values of one column, skipping failures and N/A."""
    out = []
    for row in rows:
        if row.get("status") != "OK":
            continue
        v = row.get(key, "")
        if v not in ("", "N/A", None):
            out.append(float(v))
    return out


def _table(caption: str, label: str, header: List[str],
           body_rows: List[List[str]]) -> str:
    """Assemble a complete booktabs table environment."""
    cols = "l" * 2 + "r" * (len(header) - 2)
    lines = [
        "% Auto-generated by benchmark/latex_tables.py — do not edit by hand.",
        "\\begin{table}[t]",
        "  \\centering",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        f"  \\begin{{tabular}}{{{cols}}}",
        "    \\toprule",
        "    " + " & ".join(header) + " \\\\",
        "    \\midrule",
    ]
    for row in body_rows:
        lines.append("    " + " & ".join(row) + " \\\\")
    lines += [
        "    \\bottomrule",
        "  \\end{tabular}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def _group_cells(rows: List[dict]) -> Dict[tuple, List[dict]]:
    """Group CSV rows by (model, scenario) -> {architecture: rows}."""
    cells: Dict[tuple, List[dict]] = defaultdict(list)
    for row in rows:
        cells[(row["model"], row["scenario"], row["architecture"])].append(row)
    return cells


def _bold_if(text: str, condition: bool) -> str:
    return f"\\textbf{{{text}}}" if condition else text


def generate(experiment: str, run_id: Optional[str], cfg: BenchmarkConfig) -> None:
    """Generate all LaTeX tables for one experiment's stored raw data."""
    raw_dir = cfg.results_dir / experiment / "raw"
    latex_dir = cfg.results_dir / experiment / "latex"
    latex_dir.mkdir(parents=True, exist_ok=True)

    if run_id is None:
        run_id = _latest_run_id(raw_dir)
    if run_id is None:
        print(f"latex: no raw CSV found in {raw_dir} — nothing to generate")
        return

    rows = _load_rows(raw_dir / f"{run_id}.csv")
    if not rows:
        print(f"latex: {run_id}.csv is empty — nothing to generate")
        return

    cells = _group_cells(rows)
    # Latency and routing tables use concurrency = 1 only (isolated
    # behaviour, no queueing); resource/token tables use all runs.
    cells_c1 = _group_cells([r for r in rows if r.get("concurrency") in ("1", 1)])
    # All (model, scenario) pairs, and which architectures exist.
    pairs = sorted({(m, s) for (m, s, _a) in cells})
    architectures = sorted({a for (_m, _s, a) in cells})

    exp_tex = experiment.replace("_", "-")

    # ---- latency table (concurrency = 1) --------------------------------------
    body = []
    for model, scenario in pairs:
        stats = {a: summarize(_values(cells_c1.get((model, scenario, a), []), "e2e_ms"))
                 for a in architectures}
        best = min(architectures, key=lambda a: stats[a]["mean"] or float("inf"))
        for arch in architectures:
            s = stats[arch]
            if s["mean"] == 0.0:
                continue
            body.append([
                _short_model(model),
                f"{scenario.replace('_', ' ')} ({_ARCH_LABELS.get(arch, arch)})",
                _bold_if(f"{s['mean']:.0f} $\\pm$ {s['stdev']:.0f}", arch == best),
                f"{s['median']:.0f}", f"{s['p95']:.0f}",
            ])
    tex = _table(
        f"End-to-end latency (ms) at concurrency 1 — "
        f"{experiment.replace('_', ' ')}.",
        f"tab:{exp_tex}-latency",
        ["Model", "Scenario (architecture)", "Mean $\\pm$ SD", "Median", "P95"],
        body,
    )
    (latex_dir / "latency.tex").write_text(tex, encoding="utf-8")

    # ---- CPU / memory / GPU tables -------------------------------------------------
    # Prefer the Ollama SERVER metrics (where inference happens); fall back
    # to the harness-process metrics when no server was sampled (dry runs).
    if any(_values(rows_, "server_cpu_avg")
           for rows_ in cells.values()):
        resource_tables = [
            ("server_cpu_avg", "server_cpu_peak", "\\%", "cpu.tex",
             "CPU utilisation (Ollama server)"),
            ("server_rss_avg_mb", "server_rss_peak_mb", "MB", "memory.tex",
             "RSS memory (Ollama server)"),
        ]
    else:
        resource_tables = [
            ("cpu_avg", "cpu_peak", "\\%", "cpu.tex",
             "CPU utilisation (harness process)"),
            ("rss_avg_mb", "rss_peak_mb", "MB", "memory.tex",
             "RSS memory (harness process)"),
        ]
    if any(_values(rows_, "gpu_util_avg") for rows_ in cells.values()):
        resource_tables += [
            ("gpu_util_avg", "gpu_util_peak", "\\%", "gpu.tex",
             "GPU utilisation"),
            ("vram_avg_mb", "vram_peak_mb", "MB", "vram.tex",
             "GPU memory"),
        ]
    for metric_avg, metric_peak, unit, fname, caption in resource_tables:
        body = []
        for model, scenario in pairs:
            means = {}
            for arch in architectures:
                avg_vals = _values(cells.get((model, scenario, arch), []), metric_avg)
                peak_vals = _values(cells.get((model, scenario, arch), []), metric_peak)
                if avg_vals:
                    means[arch] = (sum(avg_vals) / len(avg_vals), max(peak_vals))
            if not means:
                continue
            best = min(means, key=lambda a: means[a][0])
            for arch, (avg, peak) in means.items():
                body.append([
                    _short_model(model),
                    f"{scenario.replace('_', ' ')} ({_ARCH_LABELS.get(arch, arch)})",
                    _bold_if(f"{avg:.1f}", arch == best),
                    f"{peak:.1f}",
                ])
        tex = _table(
            f"{caption} ({unit}) — {experiment.replace('_', ' ')}.",
            f"tab:{exp_tex}-{fname[:-4]}",
            ["Model", "Scenario (architecture)", "Average", "Peak"],
            body,
        )
        (latex_dir / fname).write_text(tex, encoding="utf-8")

    # ---- token table ----------------------------------------------------------------
    body = []
    for model, scenario in pairs:
        means = {}
        for arch in architectures:
            totals = _values(cells.get((model, scenario, arch), []), "total_tokens")
            prompts = _values(cells.get((model, scenario, arch), []), "prompt_tokens")
            compls = _values(cells.get((model, scenario, arch), []), "completion_tokens")
            if totals:
                means[arch] = (
                    sum(prompts) / len(prompts) if prompts else 0,
                    sum(compls) / len(compls) if compls else 0,
                    sum(totals) / len(totals),
                )
        if not means:
            continue
        best = min(means, key=lambda a: means[a][2])
        for arch, (p, c, t) in means.items():
            body.append([
                _short_model(model),
                f"{scenario.replace('_', ' ')} ({_ARCH_LABELS.get(arch, arch)})",
                f"{p:.0f}", f"{c:.0f}",
                _bold_if(f"{t:.0f}", arch == best),
            ])
    if body:
        tex = _table(
            f"Token consumption per run — {experiment.replace('_', ' ')}.",
            f"tab:{exp_tex}-tokens",
            ["Model", "Scenario (architecture)", "Prompt", "Completion", "Total"],
            body,
        )
        (latex_dir / "tokens.tex").write_text(tex, encoding="utf-8")

    # ---- routing accuracy table (concurrency = 1) --------------------------------------
    body = []
    for model, scenario in pairs:
        accs = {}
        for arch in architectures:
            cell = cells_c1.get((model, scenario, arch), [])
            if cell:
                correct = sum(1 for r in cell if r.get("routing_correct") == "True")
                accs[arch] = 100.0 * correct / len(cell)
        if not accs:
            continue
        best = max(accs, key=accs.get)
        for arch, acc in accs.items():
            body.append([
                _short_model(model),
                f"{scenario.replace('_', ' ')} ({_ARCH_LABELS.get(arch, arch)})",
                _bold_if(f"{acc:.0f}\\%", arch == best),
            ])
    tex = _table(
        f"Routing accuracy at concurrency 1 — {experiment.replace('_', ' ')}."
        f"  For the gatekeeping scenario (unsupported request) "
        f"\\emph{{correct}} means the model selected no skill; otherwise it "
        f"means the expected skill was selected.",
        f"tab:{exp_tex}-routing",
        ["Model", "Scenario (architecture)", "Accuracy"],
        body,
    )
    (latex_dir / "routing.tex").write_text(tex, encoding="utf-8")

    # ---- throughput table (from the *_throughput.csv, if present) -------------------------
    tp_path = raw_dir / f"{run_id}_throughput.csv"
    if tp_path.exists() and tp_path.stat().st_size > 0:
        with open(tp_path, newline="", encoding="utf-8") as fh:
            records = list(csv.DictReader(fh))
        body = [
            [
                _short_model(rec["model"]),
                f"{rec['scenario'].replace('_', ' ')} "
                f"({_ARCH_LABELS.get(rec['architecture'], rec['architecture'])})",
                rec["concurrency"],
                f"{float(rec['rps']):.3f}",
                f"{float(rec['avg_latency_ms']):.0f}",
                rec["failures"],
            ]
            for rec in records
        ]
        if body:
            tex = _table(
                f"Throughput — {experiment.replace('_', ' ')}.",
                f"tab:{exp_tex}-throughput",
                ["Model", "Scenario (architecture)", "Conc.", "Req/s",
                 "Avg lat. (ms)", "Fail"],
                body,
            )
            (latex_dir / "throughput.tex").write_text(tex, encoding="utf-8")

    print(f"latex: tables written to {latex_dir}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Regenerate benchmark LaTeX tables")
    parser.add_argument("--experiment", required=True)
    parser.add_argument("--run-id", default=None,
                        help="specific run ID (default: most recent)")
    parser.add_argument("--config", type=Path, default=None)
    args = parser.parse_args()
    cfg = load_config(args.config)
    generate(args.experiment, args.run_id, cfg)


if __name__ == "__main__":
    main()
